// Writes src/react/styles.css inside `@layer glirastes` to dist/react/styles.layered.css
// (and the CJS copy). The unlayered styles.css stays the default; an app loads one of the two.
// `--stdout` prints instead of writing, `--stdin` reads the source from stdin (tests).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SOURCE = join(ROOT, 'src/react/styles.css');
const TARGETS = [join(ROOT, 'dist/react/styles.layered.css'), join(ROOT, 'dist/cjs/react/styles.layered.css')];
const HEADER = '/* glirastes — the chat styles of glirastes/react/styles.css inside `@layer glirastes`.\n'
  + '   Generated by scripts/generate-layered-styles.mjs. Load this file or styles.css, not both. */\n';

// @import, @charset and @namespace are invalid inside a block; a nested @layer would become
// glirastes.<name>; layered @font-face and @property resolve differently. None of them may be wrapped.
const UNWRAPPABLE = /@(import|charset|namespace|layer|font-face|property)\b/;

export function layerStyles(css) {
  const found = UNWRAPPABLE.exec(css);
  if (found) throw new Error(`styles.css cannot be wrapped in @layer glirastes: it contains ${found[0]}`);
  return `${HEADER}@layer glirastes {\n${css.endsWith('\n') ? css : `${css}\n`}}\n`;
}

const css = process.argv.includes('--stdin') ? readFileSync(0, 'utf8') : readFileSync(SOURCE, 'utf8');
let layered;
try {
  layered = layerStyles(css);
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
if (process.argv.includes('--stdout')) process.stdout.write(layered);
else for (const target of TARGETS) writeFileSync(target, layered);
